//! Render a parsed testscript as a Gherkin skeleton.
//!
//! Every scenario is tagged `@skeleton` and has no steps; the original txtar lines are kept as
//! comments. The BDD runner skips `@skeleton` on both tools, so an unspecified scenario can never
//! pass vacuously. Specifying a scenario means writing its steps and removing its tag.

use std::fmt::Write as _;

use crate::txtar::{Script, Test};

/// Render `script` (read from `source`, a path for the provenance header) as a feature file.
#[must_use]
pub fn render(script: &Script, source: &str) -> String {
    let mut out = String::new();
    header(&mut out, script, source);
    comment_block(&mut out, "  ", "setup (from txtar):", &script.setup);
    comment_block(&mut out, "  ", "archive files:", &script.files);
    for test in &script.tests {
        scenario(&mut out, test);
    }
    out
}

fn header(out: &mut String, script: &Script, source: &str) {
    let _ = writeln!(
        out,
        "# Generated by `cargo xtask txtar2feature` from chezmoi {source}"
    );
    let _ = writeln!(
        out,
        "# Skeleton: write each scenario's steps, then remove its @skeleton tag."
    );
    if !script.tags.is_empty() {
        let tags: Vec<String> = script.tags.iter().map(|t| format!("@{t}")).collect();
        let _ = writeln!(out, "{}", tags.join(" "));
    }
    let _ = writeln!(out, "Feature: {}", script.name);
    if let Some(issue) = script.name.strip_prefix("issue") {
        let _ = writeln!(
            out,
            "  Regression test for https://github.com/twpayne/chezmoi/issues/{issue}"
        );
    }
}

fn comment_block(out: &mut String, indent: &str, heading: &str, lines: &[String]) {
    if lines.is_empty() {
        return;
    }
    let _ = writeln!(out, "\n{indent}# {heading}");
    for line in lines {
        let _ = writeln!(out, "{indent}#   {line}");
    }
}

fn scenario(out: &mut String, test: &Test) {
    let _ = writeln!(out, "\n  @skeleton\n  Scenario: {}", test.title);
    for line in &test.lines {
        if line.trim().is_empty() {
            let _ = writeln!(out, "    #");
        } else {
            let _ = writeln!(out, "    # {line}");
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::txtar::parse;

    const SOURCE: &str = "internal/cmd/testdata/scripts/applychmod_unix.txtar";

    fn sample() -> String {
        render(
            &parse(
                "applychmod_unix",
                "[windows] skip 'UNIX only'\n\nmksourcedir\n\n# test change file mode\nchmod 777 $HOME/.file\nexec chezmoi apply --force\n\n# test that chezmoi apply is idempotent\nexec chezmoi apply\n-- golden/.file --\n# contents\n",
            ),
            SOURCE,
        )
    }

    fn parse_gherkin(text: &str) -> gherkin::Feature {
        gherkin::Feature::parse(text, gherkin::GherkinEnv::default())
            .unwrap_or_else(|e| panic!("invalid Gherkin: {e}\n{text}"))
    }

    #[test]
    fn output_is_valid_gherkin_with_one_scenario_per_test() {
        let feature = parse_gherkin(&sample());
        assert_eq!(feature.name, "applychmod_unix");
        let names: Vec<_> = feature.scenarios.iter().map(|s| s.name.as_str()).collect();
        assert_eq!(names, ["change file mode", "apply is idempotent"]);
    }

    #[test]
    fn os_tags_go_on_the_feature_and_skeleton_on_each_scenario() {
        let feature = parse_gherkin(&sample());
        assert_eq!(feature.tags, ["unix"]);
        for scenario in &feature.scenarios {
            assert_eq!(scenario.tags, ["skeleton"]);
            assert!(scenario.steps.is_empty(), "skeletons must have no steps");
        }
    }

    #[test]
    fn keeps_provenance_setup_body_and_archive_as_comments() {
        let text = sample();
        assert!(text.contains(SOURCE), "provenance header missing:\n{text}");
        assert!(text.contains("#   mksourcedir"));
        assert!(text.contains("    # chmod 777 $HOME/.file"));
        assert!(text.contains("#   golden/.file"));
    }

    #[test]
    fn issue_scripts_link_to_the_upstream_issue() {
        let text = render(&parse("issue2016", "# test a\nb\n"), "x");
        assert!(text.contains("https://github.com/twpayne/chezmoi/issues/2016"));
        parse_gherkin(&text);
    }

    #[test]
    fn awkward_titles_and_lines_still_parse() {
        let script = parse(
            "t",
            "# test that the --path-style=absolute works: \"quoted\" | piped @at\n[unix] [umask:002] cmp stdout golden/x\n\n    indented\n",
        );
        let feature = parse_gherkin(&render(&script, "x"));
        assert_eq!(
            feature.scenarios[0].name,
            "the --path-style=absolute works: \"quoted\" | piped @at"
        );
    }
}
